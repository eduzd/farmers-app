interface I18nState {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string) => string;
  loadLanguage: () => Promise<void>;
}

// A new t() per language: with the React Compiler on, components only re-run t("key") when t itself changes.
const makeT = (language: Language) => (key: string) => translations[language][key] || translations.en[key] || key;

export const useI18n = create<I18nState>((set, get) => ({
  language: "en",
  
  setLanguage: async (lang: Language) => {
    set({ language: lang, t: makeT(lang) });
    await AsyncStorage.setItem("language", lang);
  },
  
  t: makeT("en"),
  
  loadLanguage: async () => {
    const saved = await AsyncStorage.getItem("language");
    if (saved && (saved === "en" || saved === "bn")) {
      set({ language: saved, t: makeT(saved) });
    }
  },
}));
