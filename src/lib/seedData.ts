import { Company, CompanyProduct, saveAllCompanies, saveCompany, saveCompanyProducts } from "./storage";
import { getApiUrl } from "./query-client";

export async function initializeSeedData(): Promise<void> {
  try {
    const apiUrl = getApiUrl();
    const response = await fetch(new URL("/api/seed-data", apiUrl).toString());
    
    if (!response.ok) {
      console.log("Could not fetch seed data from API, using default data");
      await initializeDefaultData();
      return;
    }

    const data = await response.json();
    const companies: Company[] = data.companies.map((c: any) => ({
      id: c.id,
      ownerId: c.ownerId || `owner-${c.id}`,
      name: c.name,
      initials: c.initials,
      description: c.description,
      category: c.category,
      verified: c.verified,
      rating: c.rating,
      reviewsCount: c.reviewsCount,
      productsCount: c.productsCount,
      followersCount: c.followersCount,
      totalSales: c.totalSales,
      responseRate: c.responseRate,
      responseTime: c.responseTime || "১ ঘন্টার মধ্যে",
      shipOnTime: c.shipOnTime,
      establishedYear: c.establishedYear,
      address: c.address,
      phone: c.phone,
      email: c.email,
      businessHours: c.businessHours,
      returnPolicy: c.returnPolicy,
      shippingPolicy: c.shippingPolicy,
      paymentMethods: c.paymentMethods,
      createdAt: new Date().toISOString(),
    }));

    await saveAllCompanies(companies);

    for (const companyData of data.companies) {
      await saveCompany(companies.find((c: Company) => c.id === companyData.id)!);
      
      const products: CompanyProduct[] = (companyData.products || []).map((p: any) => ({
        id: p.id,
        companyId: companyData.id,
        name: p.name,
        description: p.description,
        price: p.price,
        unit: p.unit,
        quantity: p.quantity,
        category: p.category,
        status: p.status,
        createdAt: new Date().toISOString(),
      }));

      await saveCompanyProducts(companyData.id, products);
    }

    console.log("Seed data initialized successfully");
  } catch (error) {
    console.error("Error initializing seed data:", error);
    await initializeDefaultData();
  }
}

