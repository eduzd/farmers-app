export type Language = 'bn' | 'en';
export type TranslationKey = keyof typeof translations.bn;

export function t(key: TranslationKey, lang: Language = 'bn'): string {
  return translations[lang][key] || translations.bn[key] || key;
}

export function formatNumber(num: number, lang: Language = 'bn'): string {
  if (lang === 'bn') {
    const bnDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
    return num.toFixed(2).replace(/\d/g, (d) => bnDigits[parseInt(d)]);
  }
  return num.toFixed(2);
}

export function formatCurrency(amount: number, lang: Language = 'bn'): string {
  const formatted = formatNumber(amount, lang);
  return lang === 'bn' ? `৳${formatted}` : `৳${formatted}`;
}

export function formatWeight(kg: number, lang: Language = 'bn'): string {
  const formatted = formatNumber(kg, lang);
  return lang === 'bn' ? `${formatted} কেজি` : `${formatted} kg`;
}
